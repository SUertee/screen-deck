import { execFile } from 'node:child_process';
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const runFile = promisify(execFile);
const sourcePNG = fileURLToPath(new URL('../assets/brand/screendeck-icon-black.png', import.meta.url));
const pngSignature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
const iconSizes = [[16, 'icp4'], [32, 'icp5'], [64, 'icp6'], [128, 'ic07'], [256, 'ic08'], [512, 'ic09'], [1024, 'ic10']];
export async function writeAppIcon(destination) {
  const temporaryRoot = await mkdtemp(join(tmpdir(), 'screendeck-app-icon-'));
  try {
    const parts = [];
    for (const [size, type] of iconSizes) {
      const output = join(temporaryRoot, `${size}.png`);
      await runFile('/usr/bin/sips', ['--resampleHeightWidth', String(size), String(size), sourcePNG, '--out', output], { timeout: 30_000, maxBuffer: 64 * 1024 });
      const png = await readFile(output);
      if (png.length < 33 || !png.subarray(0, 8).equals(pngSignature) || png.toString('ascii', 12, 16) !== 'IHDR' || png.readUInt32BE(16) !== size || png.readUInt32BE(20) !== size) {
        throw new Error(`Invalid ${size}px app icon generated by sips`);
      }
      const header = Buffer.alloc(8);
      header.write(type, 0);
      header.writeUInt32BE(png.length + 8, 4);
      parts.push(header, png);
    }
    const header = Buffer.alloc(8);
    header.write('icns');
    header.writeUInt32BE(8 + parts.reduce((total, part) => total + part.length, 0), 4);
    await writeFile(destination, Buffer.concat([header, ...parts]));
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true });
  }
}
